def calculate_hidden_score(row):
    hidden_score = 100 - row["관광인지도"]
    population_score = min(abs(row["인구변화율"]) * 5, 20)

    return round(
        hidden_score * 0.4
        + population_score * 0.1
        + row["음식점수"] * 0.25
        + row["지역특색"] * 0.25,
        1,
    )


def make_kakao_map_url(place_name, region_name):
    search_text = urllib.parse.quote(
        f"{region_name} {place_name}"
    )

    return (
        f"https://map.kakao.com/link/search/"
        f"{search_text}"
    )


def split_schedule_item(value):
    parts = str(value).split("·", 1)

    if len(parts) == 2:
        return parts[0].strip(), parts[1].strip()

    return "", str(value).strip()


