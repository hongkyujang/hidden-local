# =========================================================
# 지역 리뷰
# =========================================================

with tab5:

    st.markdown("### 💬 지역 방문 리뷰")

    st.caption(
        "공모전 서비스 시연을 위한 임의의 리뷰 데이터입니다. "
        "실제 시민 작성 리뷰가 아닙니다."
    )

    reviews = REVIEW_DATA.get(
        row["지역"],
        [],
    )

    if reviews:

        average_rating = round(
            sum(
                review[1]
                for review in reviews
            )
            / len(reviews),
            1,
        )

        review_top1, review_top2 = st.columns(2)

        with review_top1:

            st.metric(
                "⭐ 평균 별점",
                f"{average_rating} / 5.0",
            )

        with review_top2:

            st.metric(
                "💬 리뷰",
                f"{len(reviews)}개",
            )

        st.divider()

        for (
            reviewer,
            rating,
            review_text,
        ) in reviews:

            review_col1, review_col2 = st.columns(
                [1, 5]
            )

            with review_col1:

                st.markdown(
                    f"**{reviewer}**"
                )

                stars = (
                    "★" * int(rating)
                    + "☆" * (5 - int(rating))
                )

                st.markdown(
                    f"<span class='review-star'>"
                    f"{stars} {rating:.1f}"
                    f"</span>",
                    unsafe_allow_html=True,
                )

            with review_col2:

                st.markdown(
                    f"**{review_text}**"
                )

                st.caption(
                    "지역 방문자 리뷰 · 시연용 임의 데이터"
                )

            st.divider()

    else:

        st.info(
            "아직 등록된 지역 리뷰가 없습니다."
        )


